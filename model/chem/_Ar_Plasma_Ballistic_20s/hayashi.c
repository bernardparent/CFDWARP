/*
Electron-argon cross-sections of the Hayashi database (M. Hayashi, NIFS-DATA-72, 2003),
as exported from LXCat (www.lxcat.net) on 16 May 2026: the elastic momentum transfer
cross-section, 25 excitation channels and the ionization channel.

The tables are the LXCat values unchanged: energies in eV, cross-sections in m2.
Between two tabulated energies the cross-section is interpolated linearly. Below the
first point it is zero for the inelastic channels (the first point is the threshold),
and above the last point it is held at the last tabulated value.

Inelastic channels are numbered k=0..HAYASHI_NUMINEL-1 in order of increasing threshold;
the last one, k=HAYASHI_INEL_IZ, is the ionization.
*/

