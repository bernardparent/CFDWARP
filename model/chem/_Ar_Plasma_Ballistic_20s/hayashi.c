static double _sigma_from_table(const double *eps_table, const double *sigma_table, long numpoints, double eps){
  long lo,hi,mid;
  if (eps<=eps_table[0]) return(sigma_table[0]);
  if (eps>=eps_table[numpoints-1]) return(sigma_table[numpoints-1]);
  lo=0;
  hi=numpoints-1;
  while (hi-lo>1){
    mid=(lo+hi)/2;
    if (eps_table[mid]>eps) hi=mid; else lo=mid;
  }
  return(sigma_table[lo]+(sigma_table[hi]-sigma_table[lo])*(eps-eps_table[lo])/(eps_table[hi]-eps_table[lo]));
}


/* elastic momentum transfer cross-section in m2 at the electron energy eps in eV */
double _sigma_el_Hayashi(double eps){
  return(_sigma_from_table(el_eps, el_sigma, 63, eps));
}


/* cross-section in m2 of the inelastic channel k at the electron energy eps in eV */
double _sigma_inel_Hayashi(long k, double eps){
  if (k<0 || k>=HAYASHI_NUMINEL) fatal_error("Inelastic channel k=%ld out of range in _sigma_inel_Hayashi().",k);
  if (eps<Deltaeps_inel[k]) return(0.0);
  return(_sigma_from_table(eps_inel[k], sigma_inel[k], numpoints_inel[k], eps));
}


/* energy lost in eV by the electron in the inelastic channel k (the threshold) */
double _Deltaeps_inel_Hayashi(long k){
  if (k<0 || k>=HAYASHI_NUMINEL) fatal_error("Inelastic channel k=%ld out of range in _Deltaeps_inel_Hayashi().",k);
  return(Deltaeps_inel[k]);
}


/* maximum over the electron energy of sum_k sigma_k*Deltaeps_k in m2 eV, ionization included 
   (the bracket of Eq. 10 of parent2026 divided by N_Ar); since every cross-section is piecewise linear 
   in the energy, the maximum is attained at one of the tabulated energies */
double _maxloss_Hayashi(double *epsmax){
  long k,k2,i;
  double loss,lossmax;
  lossmax=0.0;
  *epsmax=0.0;
  for (k=0; k<HAYASHI_NUMINEL; k++){
    for (i=0; i<numpoints_inel[k]; i++){
      loss=0.0;
      for (k2=0; k2<HAYASHI_NUMINEL; k2++) loss+=_sigma_inel_Hayashi(k2,eps_inel[k][i])*Deltaeps_inel[k2];
      if (loss>lossmax){
        lossmax=loss;
        *epsmax=eps_inel[k][i];
      }
    }
  }
  return(lossmax);
}
